// Builds demo/data.ts from seed/acme-precision (CSVs and docs), so the demo
// shop ships with the app instead of being read from the repo at runtime.
//   pnpm --filter @repo/database generate-demo
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readSeed } from "../demo/read";

const SEED = join(import.meta.dirname, "../../../seed/acme-precision");
const docs = Object.fromEntries(
  readdirSync(join(SEED, "docs")).map((f) => [
    f,
    readFileSync(join(SEED, "docs", f), "utf8"),
  ])
);
const data = { ...readSeed(SEED), docs };
writeFileSync(
  join(import.meta.dirname, "../demo/data.ts"),
  `// Generated by scripts/generate-demo.ts from seed/acme-precision. Don't edit.\n\nexport const DEMO = ${JSON.stringify(data, null, 2)} as const;\n`
);
console.log("Wrote demo/data.ts");
